/**
 * Public read/write API for share page annotations, no login needed. Anonymous readers claim their own annotations with a self-generated guest key;
 * the server stores only its sha256 (authorKeyHash) and never sends this hash in responses.
 * When the author posts while logged in, isOwner is set and the frontend shows the 「作者」 (Author) badge.
 */
import { NextResponse } from "next/server";
import { auth } from "@/auth";
import { prisma } from "@/lib/prisma";
import {
  SHARE_COMMENT_CAP,
  commentJson,
  findEnabledShare,
  hashGuestKey,
} from "@/lib/share";
import { tk } from "@/i18n/t";

type Params = { params: Promise<{ token: string }> };

/** Annotation list (public). With an x-guest-key header, marks "my own" so they can still be edited/deleted after refresh */
export async function GET(req: Request, { params }: Params) {
  const { token } = await params;
  const share = await findEnabledShare(token);
  if (!share) return NextResponse.json({ error: tk("分享不存在或已关闭") }, { status: 404 });

  const key = req.headers.get("x-guest-key") ?? "";
  const session = await auth();
  const viewer = {
    keyHash: key ? hashGuestKey(key) : "",
    isOwner: session?.user?.id === share.userId,
  };
  const comments = await prisma.shareComment.findMany({
    where: { shareId: share.id },
    orderBy: { createdAt: "asc" },
  });
  return NextResponse.json(comments.map((c) => commentJson(c, viewer)));
}

/** Add an annotation/reply (public, no login needed; posts by the logged-in author are marked isOwner) */
export async function POST(req: Request, { params }: Params) {
  const { token } = await params;
  const share = await findEnabledShare(token);
  if (!share) return NextResponse.json({ error: tk("分享不存在或已关闭") }, { status: 404 });
  if (!share.allowComment) {
    return NextResponse.json({ error: tk("该分享未开放批注") }, { status: 403 });
  }

  const body = await req.json().catch(() => ({}));
  const text = typeof body.body === "string" ? body.body.trim().slice(0, 2000) : "";
  if (!text) return NextResponse.json({ error: tk("批注内容不能为空") }, { status: 400 });
  // The key is generated by the frontend and stored only locally, so switching browsers loses your annotations; an acceptable trade-off, annotations aren't account data
  const key = typeof body.key === "string" ? body.key.slice(0, 64) : "";
  const parentId = typeof body.parentId === "string" ? body.parentId : null;

  const session = await auth();
  const isOwner = session?.user?.id === share.userId;
  // 「作者」「访客」 (Author/Guest) are stored in the annotation's author field; they're data, not UI copy
  const author = isOwner
    // i18n-ignore
    ? session?.user?.name?.trim() || "作者"
    // i18n-ignore
    : (typeof body.author === "string" && body.author.trim().slice(0, 30)) || "访客";

  const anchorType = body.anchorType === "media" ? "media" : "text";
  // Replies must attach to a top-level annotation on this share
  if (parentId) {
    const parent = await prisma.shareComment.findFirst({
      where: { id: parentId, shareId: share.id, parentId: null },
      select: { id: true },
    });
    if (!parent) return NextResponse.json({ error: tk("批注不存在") }, { status: 404 });
  } else {
    const anchorText = typeof body.anchorText === "string" ? body.anchorText.slice(0, 2000) : "";
    if (!anchorText.trim()) {
      return NextResponse.json({ error: tk("缺少批注锚点") }, { status: 400 });
    }
  }

  // Counting and inserting aren't in one transaction, so concurrency may slightly exceed the cap; this only stops spam, it needn't be exact
  const total = await prisma.shareComment.count({ where: { shareId: share.id } });
  if (total >= SHARE_COMMENT_CAP) {
    return NextResponse.json({ error: tk("该分享的批注数已达上限") }, { status: 429 });
  }

  const created = await prisma.shareComment.create({
    data: {
      shareId: share.id,
      parentId,
      author,
      // Author annotations don't record a guest key (the session is enough to identify them); an empty string means "nobody can claim this one"
      authorKeyHash: !isOwner && key ? hashGuestKey(key) : "",
      isOwner,
      anchorType: parentId ? "text" : anchorType,
      anchorText: parentId
        ? ""
        : (typeof body.anchorText === "string" ? body.anchorText.slice(0, 2000) : ""),
      anchorPrefix: parentId
        ? ""
        : (typeof body.anchorPrefix === "string" ? body.anchorPrefix.slice(0, 64) : ""),
      // The same text may appear multiple times in the body; anchorIndex records which occurrence. Replies attach to the parent and need no anchor, so always 0
      anchorIndex:
        !parentId && Number.isInteger(body.anchorIndex) && body.anchorIndex >= 0
          ? Math.min(body.anchorIndex, 9999)
          : 0,
      body: text,
    },
  });
  return NextResponse.json(
    commentJson(created, { keyHash: created.authorKeyHash, isOwner })
  );
}
